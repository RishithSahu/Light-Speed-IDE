#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn srgb_conversion_matches_the_reference_curve() {
        for component in [0u8, 1, 32, 64, 128, 200, 255] {
            let value = component as f32 / 255.0;
            let expected = if value <= 0.040_45 {
                value / 12.92
            } else {
                ((value + 0.055) / 1.055f32).powf(2.4)
            };
            let actual = srgb_to_linear(component);
            assert!(
                (actual - expected).abs() < 0.002,
                "component {component}: {actual} vs {expected}"
            );
        }
    }

    #[test]
    fn colors_keep_their_srgb_values_for_text() {
        let color = Color::rgb(0xD6, 0xDC, 0xE4);
        assert_eq!(color.srgb, [0xD6, 0xDC, 0xE4, 255]);
    }
}
